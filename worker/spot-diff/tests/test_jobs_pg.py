"""대기열 SQL — 실제 PostgreSQL 에서만 의미가 있다(SKIP LOCKED·ON CONFLICT). SPOT_TEST_DATABASE_URL 이 없으면 건너뛴다.

테스트 전용 스키마를 만들고 V143 의 필요한 열만 흉내 낸 표를 둔다(운영 스키마를 건드리지 않는다).
"""
import json
import os
import uuid

import pytest

psycopg = pytest.importorskip("psycopg")

from spot_worker import config, jobs, pipeline  # noqa: E402

URL = os.environ.get("SPOT_TEST_DATABASE_URL")
pytestmark = pytest.mark.skipif(not URL, reason="SPOT_TEST_DATABASE_URL 없음")

DDL = """
create table spot_puzzles (
  id bigint generated by default as identity primary key, couple_id bigint, puzzle_date date,
  source_type varchar(20), source_id bigint, source_url varchar(1000), image_a_url varchar(1000), image_b_url varchar(1000),
  width int, height int, layout_json text, seed bigint, level varchar(10), generator_version varchar(20),
  status varchar(20) not null, expire_reason varchar(20), fail_reason varchar(500),
  updated_at timestamp not null default now());
create table spot_puzzle_jobs (
  id bigint generated by default as identity primary key, puzzle_id bigint not null references spot_puzzles(id),
  status varchar(10) not null, candidates text not null, seed bigint not null, attempts int not null default 0,
  locked_at timestamp, error varchar(500), created_at timestamp not null default now(), updated_at timestamp not null default now(),
  ai_calls int not null default 0);
create table spot_photo_sizes (
  id bigint generated by default as identity primary key, url varchar(1000) not null unique,
  width int not null, height int not null, checked_at timestamp not null default now());
"""


@pytest.fixture
def conn():
    schema = "spot_test_" + uuid.uuid4().hex[:8]
    c = psycopg.connect(URL, autocommit=True)
    c.execute(f"create schema {schema}")
    c.execute(f"set search_path to {schema}")
    c.execute(DDL)
    yield c
    c.execute(f"drop schema {schema} cascade")
    c.close()


def _job(conn, status="QUEUED"):
    pid = conn.execute("insert into spot_puzzles (status) values ('PENDING') returning id").fetchone()[0]
    conn.execute("insert into spot_puzzle_jobs (puzzle_id, status, candidates, seed) values (%s, %s, %s, 5)",
                 (pid, status, json.dumps([{"type": "POST", "id": 1, "url": "https://x"}])))
    return pid


def _second(conn):
    c2 = psycopg.connect(URL, autocommit=True)
    c2.execute("set search_path to " + conn.execute("show search_path").fetchone()[0])
    return c2


def test_두_worker_가_동시에_집어도_같은_작업을_두_번_집지_않는다(conn):
    _job(conn)
    _job(conn)
    c2 = _second(conn)
    try:
        # c2 가 첫 작업 행을 잠근 채로 있는 동안 conn 이 집으면 두 번째 작업이 나와야 한다(SKIP LOCKED)
        with c2.transaction():
            locked = c2.execute("select id from spot_puzzle_jobs order by id limit 1 for update").fetchone()[0]
            got = jobs.claim(conn)
            assert got is not None and got.id != locked
        again = jobs.claim(c2)
        assert again.id == locked
        assert jobs.claim(conn) is None
    finally:
        c2.close()


def test_READY_는_PENDING_인_퍼즐에만_쓴다(conn):
    pid = _job(conn)
    job = jobs.claim(conn)
    out = pipeline.Outcome("READY", candidate={"type": "POST", "id": 9, "url": "https://src"}, seed=3,
                           width=1600, height=1200, layout={"diffs": []})
    assert jobs.finish_ready(conn, job, out, "https://a", "https://b") is True
    row = conn.execute("select status, image_a_url, seed, source_id from spot_puzzles where id = %s", (pid,)).fetchone()
    assert row == ("READY", "https://a", 3, 9)

    # 그사이 닫힌 퍼즐 — 결과를 쓰지 않고 False(올린 이미지는 호출자가 지운다)
    pid2 = _job(conn)
    job2 = jobs.claim(conn)
    conn.execute("update spot_puzzles set status = 'EXPIRED' where id = %s", (pid2,))
    assert jobs.finish_ready(conn, job2, out, "https://a2", "https://b2") is False
    assert conn.execute("select image_a_url from spot_puzzles where id = %s", (pid2,)).fetchone()[0] is None


def test_사진_부족과_실패는_퍼즐_상태로_남는다(conn):
    pid = _job(conn)
    jobs.finish_status(conn, jobs.claim(conn), "NOT_ENOUGH_PHOTOS", "조건을 채운 사진 3장")
    assert conn.execute("select status, fail_reason from spot_puzzles where id = %s", (pid,)).fetchone() == \
        ("NOT_ENOUGH_PHOTOS", "조건을 채운 사진 3장")
    pid2 = _job(conn)
    jobs.finish_status(conn, jobs.claim(conn), "FAILED", "x" * 900)
    status, reason = conn.execute("select status, fail_reason from spot_puzzles where id = %s", (pid2,)).fetchone()
    assert status == "FAILED" and len(reason) == 500
    assert conn.execute("select status from spot_puzzle_jobs where puzzle_id = %s", (pid2,)).fetchone()[0] == "FAILED"


def test_죽은_worker_의_작업은_다시_집고_횟수를_넘으면_FAILED(conn):
    pid = _job(conn)
    for _ in range(config.MAX_ATTEMPTS):
        job = jobs.claim(conn)
        assert job is not None
        # worker 가 죽었다 — RUNNING 인 채 오래됨
        conn.execute("update spot_puzzle_jobs set locked_at = now() - interval '1 hour' where id = %s", (job.id,))
    assert jobs.claim(conn) is None
    assert conn.execute("select status from spot_puzzles where id = %s", (pid,)).fetchone()[0] == "FAILED"


def test_크기_캐시는_같은_주소를_덮어쓴다(conn):
    jobs.save_sizes(conn, [("https://p/1", 100, 200), ("https://p/2", 3000, 2000)])
    jobs.save_sizes(conn, [("https://p/1", 1200, 1000)])
    assert jobs.cached_sizes(conn, ["https://p/1", "https://p/2", "https://p/3"]) == \
        {"https://p/1": (1200, 1000), "https://p/2": (3000, 2000)}


def test_AI_호출_수를_쌓고_최근_24시간만_센다_상한이면_미룬다(conn):
    _job(conn)
    job = jobs.claim(conn)
    jobs.record_ai_calls(conn, job, 3)
    jobs.record_ai_calls(conn, job, 0)
    assert jobs.ai_calls_last_day(conn) == 3
    conn.execute("update spot_puzzle_jobs set updated_at = now() - interval '25 hours' where id = %s", (job.id,))
    assert jobs.ai_calls_last_day(conn) == 0

    _job(conn)
    job2 = jobs.claim(conn)
    assert job2.attempts == 1
    jobs.defer(conn, job2, "AI 일일 호출 상한 200/200")
    status, attempts, locked = conn.execute(
        "select status, attempts, locked_at from spot_puzzle_jobs where id = %s", (job2.id,)).fetchone()
    assert (status, attempts, locked) == ("QUEUED", 0, None)   # 집은 횟수를 되돌려 상한 탓에 FAILED 로 닫히지 않는다
