ALTER TABLE workout_routine_exercises ADD COLUMN muscle_group VARCHAR(20);
ALTER TABLE workout_routine_exercises ADD COLUMN equipment VARCHAR(30);

ALTER TABLE workout_sets ADD COLUMN exercise_catalog_id BIGINT REFERENCES exercise_catalog (id);
ALTER TABLE workout_sets ADD COLUMN muscle_group VARCHAR(20);
ALTER TABLE workout_sets ADD COLUMN equipment VARCHAR(30);

-- 3) 운동 기록이 어느 루틴에서 시작됐는지 연결 — 스마트 루틴 동기화(①)의 전제.
--    루틴이 삭제돼도 과거 기록은 남아야 하므로 SET NULL.
ALTER TABLE workouts
    ADD COLUMN source_routine_id BIGINT REFERENCES workout_routines (id) ON DELETE SET NULL;
CREATE INDEX idx_workouts_source_routine ON workouts (source_routine_id);

-- 4) 세트별 실제 수행 기록(무게/횟수/완료 여부) — 지금까지 workout_sets 한 행이
--    "종목당 N세트 x 무게 x 횟수" 하나의 평균값만 담고 있어, 세트마다 다른 무게/횟수를
--    남기거나(예: 1세트 60kg x10, 2세트 55kg x8) 직전 세트 값을 세트 단위로 프리필(④)할 수 없었다.
CREATE TABLE workout_set_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_set_id BIGINT  NOT NULL REFERENCES workout_sets (id) ON DELETE CASCADE,
    set_no         INT     NOT NULL,
    weight_kg      DECIMAL(6, 2),
    reps           INT,
    completed      BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_workout_set_entries_set ON workout_set_entries (workout_set_id);
