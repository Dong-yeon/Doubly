-- 운동 기능 확장 0단계 — 공통 데이터 기반
-- 1) 종목 카탈로그: 자극 부위(muscle_group)/기구(equipment) 태그의 출처.
--    대체 종목 추천(②), 자극 부위 시각화(BurnFit 벤치마킹), AI 추천 고도화(Fitbod 벤치마킹)가
--    전부 이 태그에 의존하므로 가장 먼저 세운다.
CREATE TABLE exercise_catalog (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    category     VARCHAR(20)  NOT NULL,                    -- 근력 / 유산소 / 유연성
    muscle_group VARCHAR(20)  NOT NULL,                     -- 가슴/등/어깨/하체/팔/코어/전신 등
    equipment    VARCHAR(30),                               -- 바벨/덤벨/머신/케이블/맨몸 등
    created_by   BIGINT REFERENCES users (id),               -- NULL = 시스템 기본 제공, 값 있으면 사용자 커스텀 종목
    created_at   TIMESTAMP    NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_exercise_catalog_muscle_group ON exercise_catalog (muscle_group);

