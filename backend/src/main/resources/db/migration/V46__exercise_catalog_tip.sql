-- 종목 카탈로그에 TIP(자세 큐) 컬럼 추가 — 운동 세션 화면에서 종목별 안내 카드로 노출한다.
-- nullable: 사용자가 직접 추가한 커스텀 종목은 TIP이 없을 수 있다(그때는 카드 자체를 숨긴다).
ALTER TABLE exercise_catalog ADD COLUMN tip VARCHAR(200);

UPDATE exercise_catalog SET tip = CASE name
    -- 가슴
    WHEN '벤치프레스' THEN '견갑골을 모아 고정하고, 바가 가슴 중앙에 닿을 때까지 컨트롤하며 내려요.'
    WHEN '덤벨 프레스' THEN '손목을 곧게 펴고, 팔꿈치가 어깨보다 아래로 처지지 않게 밀어 올려요.'
    WHEN '인클라인 벤치프레스' THEN '벤치 각도는 30~45도로, 바를 쇄골 쪽으로 내려 상부 가슴을 자극해요.'
    WHEN '푸시업' THEN '손은 어깨너비보다 살짝 넓게, 몸을 일자로 유지하며 코어에 힘을 줘요.'
    WHEN '케이블 크로스오버' THEN '팔꿈치를 살짝 굽힌 채로 호를 그리듯 모아, 가슴 중앙에서 짜내듯 조여요.'
    WHEN '딥스' THEN '상체를 살짝 앞으로 기울이고, 어깨가 으쓱 올라가지 않게 견갑골을 내려 고정해요.'
    -- 등
    WHEN '데드리프트' THEN '허리는 중립을 유지하고, 바를 몸에 붙인 채 바닥을 밀어내듯 일어나요.'
    WHEN '바벨 로우' THEN '상체 각도를 고정하고, 팔이 아니라 등으로 당겨 배꼽 쪽으로 끌어와요.'
    WHEN '랫풀다운' THEN '가슴을 펴고 바를 쇄골까지 당기며, 어깨가 귀 쪽으로 올라가지 않게 해요.'
    WHEN '풀업' THEN '턱이 바 위로 넘어갈 때까지 당기고, 내려올 때도 천천히 컨트롤해요.'
    WHEN '시티드 케이블 로우' THEN '등을 곧게 펴고 팔꿈치를 몸통에 붙여 당기며, 견갑골을 모아 조여요.'
    -- 어깨
    WHEN '오버헤드 프레스' THEN '코어에 힘을 주고 갈비뼈가 앞으로 뜨지 않게, 바를 정수리 뒤로 밀어 올려요.'
    WHEN '덤벨 숄더프레스' THEN '팔꿈치가 완전히 잠기지 않게, 어깨 높이에서 바로 위로 밀어 올려요.'
    WHEN '사이드 레터럴 레이즈' THEN '팔꿈치를 살짝 굽히고, 어깨 높이까지만 천천히 옆으로 들어 올려요.'
    WHEN '페이스 풀' THEN '팔꿈치를 높게 유지하고 줄을 얼굴 쪽으로 당기며 후면 삼각근을 조여요.'
    -- 하체
    WHEN '스쿼트' THEN '발바닥 전체로 바닥을 밀고, 무릎과 발끝 방향을 맞춰 안정적으로 내려가요.'
    WHEN '레그프레스' THEN '허리가 패드에서 뜨지 않는 범위까지만 내리고, 무릎을 안쪽으로 모으지 않아요.'
    WHEN '런지' THEN '앞무릎이 발끝을 넘지 않게, 상체는 곧게 세운 채 수직으로 내려가요.'
    WHEN '레그컬' THEN '골반이 뜨지 않게 고정하고, 발목을 당겨 종아리 근육까지 자극해요.'
    WHEN '레그익스텐션' THEN '무릎 관절과 패드 축을 맞추고, 반동 없이 천천히 펴고 내려요.'
    WHEN '힙쓰러스트' THEN '턱을 당기고 갈비뼈를 내린 채, 엉덩이로 밀어 올려 정점에서 짜듯 조여요.'
    -- 팔
    WHEN '바벨 컬' THEN '팔꿈치를 몸통에 고정하고, 상체 반동 없이 아래팔로만 들어 올려요.'
    WHEN '덤벨 컬' THEN '손목을 곧게 펴고, 팔꿈치 위치를 고정한 채 천천히 감아올려요.'
    WHEN '해머 컬' THEN '손바닥이 서로 마주보게 잡고, 팔꿈치를 고정한 채 들어 올려요.'
    WHEN '트라이셉스 익스텐션' THEN '팔꿈치가 벌어지지 않게 고정하고, 아래팔만 움직여 완전히 펴줘요.'
    -- 코어
    WHEN '플랭크' THEN '엉덩이가 뜨거나 처지지 않게, 몸을 일자로 유지하며 배에 힘을 줘요.'
    WHEN '크런치' THEN '허리는 바닥에 붙인 채, 상체를 명치부터 말아 올린다는 느낌으로 일으켜요.'
    WHEN '행잉 레그레이즈' THEN '반동 없이 골반을 말아 올리며, 다리는 천천히 컨트롤하며 내려요.'
    WHEN '케이블 크런치' THEN '엉덩이를 축으로 고정하고, 허리를 둥글게 말아 복근을 짜내요.'
    -- 유산소
    WHEN '러닝' THEN '착지는 발 중간~앞쪽으로, 상체는 살짝 앞으로 기울여 자연스럽게 팔을 흔들어요.'
    WHEN '사이클' THEN '안장 높이는 페달이 가장 아래일 때 무릎이 살짝 굽는 정도로 맞춰요.'
    WHEN '로잉머신' THEN '다리로 밀고 → 허리를 세우고 → 팔로 당기는 순서를 지켜 반동을 줄여요.'
    -- 유연성
    WHEN '폼롤러 스트레칭' THEN '숨을 천천히 내쉬며 뭉친 부위에서 10~20초씩 머물러 압박을 풀어줘요.'
    WHEN '요가 스트레칭' THEN '통증이 아닌 시원한 느낌까지만 늘리고, 호흡을 참지 말고 자연스럽게 쉬어요.'
    ELSE tip
END;
