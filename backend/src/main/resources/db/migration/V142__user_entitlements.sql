-- 소유권 — "이 사람은 이것을 영구히 가졌다" (2026-10-14, docs/DUBLY_PLUS_PLAN_2026-10-14.md S2)
--
-- 첫 소유권은 AD_FREE(Dubly Plus 영구, 스토어 상품 plus_lifetime). 1개월·1년 구독은 여기 오지 않고 subscriptions 그대로다.
-- Plan enum 에 소유권을 끼우지 않는다 — 끼우면 영구권 = PRO = PRO 한도가 되어 1회 결제에 매달 원가가 붙는다
-- (docs/MONETIZATION_LIFETIME_2026-10-13.md §2, B안).
--
-- (user_id, entitlement) 에 UNIQUE 를 걸지 않는다: 환불(REVOKED) 뒤 다시 사면 두 번째 행이 생겨야 한다. 판정은
-- "GRANTED 행이 하나라도 있나"다. 관계가 끝나도 거두지 않는다(산 사람의 것 — V96 과 같은 판단) — RelationRecordPurger 대상 아님.
-- H2 호환 구문만 사용(CLAUDE.md 4절).

CREATE TABLE user_entitlements (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id),
    entitlement     VARCHAR(20)  NOT NULL,          -- AD_FREE
    store           VARCHAR(20)  NOT NULL,          -- GOOGLE_PLAY | APP_STORE | MANUAL
    product_id      VARCHAR(100) NOT NULL,          -- plus_lifetime
    transaction_id  VARCHAR(255) NOT NULL UNIQUE,   -- Play purchaseToken / App Store transactionId — 검증 재호출·복원 멱등
    status          VARCHAR(20)  NOT NULL,          -- GRANTED | REVOKED
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_user_entitlements_user ON user_entitlements (user_id, entitlement);
