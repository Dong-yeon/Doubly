-- 스티커 낱개 판매를 접고 구독으로 몬다 (2026-09-22)
--
-- <b>왜</b>: 낱개로 팔려면 팩 하나마다 스토어 상품을 하나씩 등록해야 한다 — 그것도
-- 양쪽 스토어에, 애플은 심사까지 지나서. 라인·카카오가 그렇게 하지 않는 이유가 이것이고,
-- 그들은 자체 캐시(코인·초코)를 충전시켜 카탈로그를 서버에 둔다. 캐시는 지갑·원장·환불·
-- 약관이 딸려오는 결제 시스템 한 채라, 유료 팩이 둘뿐인 지금 규모에서는 과하다.
--
-- 그래서 <b>구독 하나로 판다</b>(카카오의 '이모티콘 플러스'와 같은 자리). 이 두 팩은
-- 원래도 is_pro_only 라 구독자에게는 이미 열려 있었다 — 여기서 지우는 것은 "구독 말고
-- 낱개로도 살 수 있다"는 길뿐이다.
--
-- <b>가격만 지운다. 잠금은 그대로다.</b>
--   is_pro_only = TRUE, price = 0  →  isFreeForEveryone() false (여전히 PRO 전용)
--                                     isPurchasable()     false (낱개 구매 불가)
-- 앱도 저절로 맞는다: 상점의 값 칩이 PRO 배지로 바뀌고, 채팅의 잠금 해제 줄은
-- "가격이 있으면 상점, 없으면 업그레이드"라 이제 업그레이드 시트로 간다. 예전에는
-- 값이 붙어 있어 상점으로 보냈는데, 정작 상점은 무드·터치를 목록에서 빼 두어
-- <b>아무것도 없는 화면으로 보내는 막다른 길</b>이었다.
--
-- 되돌리려면 price 를 올리고 스토어에 sticker_pack_<id 소문자> 상품을 등록하면 된다.
-- 그때 StickerPackSyncTest 의 '낱개로 파는 팩은 없다' 가 먼저 빨개진다 — 그게 의사결정
-- 지점이라 일부러 테스트로 세워 뒀다.
--
-- 이미 낱개로 산 사람의 user_sticker_purchases 행은 건드리지 않는다. 산 것은 산 것이고,
-- 구독을 끊어도 그 팩은 계속 열린다(StickerService.ownedPackIds).
-- (H2 호환 구문만 사용 — 테스트가 동일 마이그레이션을 적용한다)
UPDATE sticker_packs SET price = 0 WHERE id IN ('MOOD_PREMIUM', 'TOUCH_PREMIUM');
