-- 이 기기에 앱이 만든 안드로이드 알림 채널 세트의 버전 — 있으면 푸시에 카테고리별 channelId 를 싣는다.
--
-- 왜 필요한가: 채널을 만들지 않던 동안 모든 푸시가 expo-notifications 의 대체 채널(배지 켜짐) 하나로 왔다.
-- 삼성 런처는 앱이 꺼져 있으면 트레이 알림 수로 아이콘 숫자를 그려서, 채팅을 다 읽어도 럽슐랭·피드 알림이
-- 숫자로 남았다(docs/chat-unread-badge_2026-10-08.md "채널 분리"). 앱이 카테고리별 채널(채팅만 배지 켜짐)을
-- 만들고, 서버가 그 채널로 보내야 고쳐진다.
--
-- 서버가 아무 기기에나 channelId 를 실으면 안 되는 이유: 채널을 만들기 전 버전의 앱에는 그 채널이 없다.
-- Expo 문서는 없는 채널로 온 알림이 표시되지 않을 수 있다고 적고 있다. 그래서 앱이 채널을 만든 뒤 토큰을
-- 등록할 때 이 값을 함께 보내고, 서버는 값이 있는 토큰에만 channelId 를 싣는다.
--
-- 채널의 중요도·배지 여부는 한 번 만들면 앱이 바꿀 수 없다(안드로이드 규칙). 그래서 바꿔야 할 땐 새 id 의
-- 채널을 만들고 이 버전을 올린다 — 서버는 버전으로 어느 id 를 실을지 고른다.
--
-- 기존 행은 null(= 채널 없음)로 둔다. 앱이 다음에 시작하며 토큰을 다시 등록할 때 채워진다.
