-- 종목 카탈로그에 "이게 무슨 동작인지" 설명하는 한 줄을 추가한다.
--
-- 기존 tip(자세 큐)은 <b>이미 그 운동을 아는 사람</b>에게 주는 교정 문구다 — 예를 들어 풀업의
-- tip 은 "턱이 바 위로 넘어갈 때까지 당기고..."인데, 풀업이 뭔지 모르는 사람에게는 아무것도
-- 알려주지 못한다. description 은 그 앞 단계, 즉 "철봉에 매달려 몸을 끌어올린다"는 동작 자체를
-- 설명한다. 둘은 대상 독자가 다르므로 컬럼을 분리한다(emoji/breathing_cue 를 tip 옆에 따로 둔 것과 같은 원칙).
--
-- 시범 이미지·영상은 PLAN.md 에서 저작권·용량 문제로 Non-goal 로 두고 "외부 링크로 대체 가능"
-- 이라 결정했으므로, 여기서는 텍스트만 담고 프론트가 유튜브 검색 링크를 함께 제공한다.
ALTER TABLE exercise_catalog ADD COLUMN description VARCHAR(300);

-- 커스텀 종목(이름이 매칭 안 되는 행)은 ELSE 로 NULL 유지 — 프론트가 없으면 그냥 숨긴다.
UPDATE exercise_catalog SET description = CASE name
    WHEN '벤치프레스' THEN '벤치에 누워 가슴 위의 바벨을 밀어 올렸다 내리는 대표적인 가슴 운동이에요.'
    WHEN '덤벨 프레스' THEN '벤치에 누워 양손 덤벨을 가슴 옆에서 위로 밀어 올리는 운동이에요.'
    WHEN '인클라인 벤치프레스' THEN '등받이를 30~45도 세운 벤치에 누워 바벨을 밀어 올려요. 가슴 윗부분을 집중적으로 씁니다.'
    WHEN '푸시업' THEN '엎드려 손으로 바닥을 밀어 몸을 올렸다 내리는 맨몸 가슴 운동이에요.'
    WHEN '케이블 크로스오버' THEN '양옆 케이블 손잡이를 잡고 팔을 몸 앞쪽으로 모으는 운동이에요. 가슴을 조이는 느낌으로 합니다.'
    WHEN '딥스' THEN '평행봉에 몸을 지탱하고 팔을 굽혔다 펴며 몸을 올렸다 내리는 운동이에요.'
    WHEN '데드리프트' THEN '바닥의 바벨을 등과 다리 힘으로 잡아당겨 일어서는 전신 운동이에요.'
    WHEN '바벨 로우' THEN '상체를 숙인 자세에서 바벨을 배 쪽으로 당기는 등 운동이에요.'
    WHEN '랫풀다운' THEN '앉아서 머리 위 바를 가슴 쪽으로 당겨 내리는 등 운동이에요. 풀업의 머신 버전입니다.'
    WHEN '풀업' THEN '철봉에 매달려 팔과 등 힘으로 몸을 끌어올리는 맨몸 등 운동이에요.'
    WHEN '시티드 케이블 로우' THEN '앉아서 케이블 손잡이를 배 쪽으로 당기는 등 운동이에요.'
    WHEN '오버헤드 프레스' THEN '서서 어깨 높이의 바벨을 머리 위로 밀어 올리는 어깨 운동이에요.'
    WHEN '덤벨 숄더프레스' THEN '양손 덤벨을 어깨 높이에서 머리 위로 밀어 올리는 어깨 운동이에요.'
    WHEN '사이드 레터럴 레이즈' THEN '양손 덤벨을 몸 옆으로 어깨 높이까지 들어 올리는 운동이에요. 어깨 옆면을 씁니다.'
    WHEN '페이스 풀' THEN '케이블 로프를 얼굴 쪽으로 당기며 팔꿈치를 벌리는 운동이에요. 어깨 뒷면과 자세 교정에 좋아요.'
    WHEN '스쿼트' THEN '바벨을 어깨에 얹고 앉았다 일어서는 대표적인 하체 운동이에요.'
    WHEN '레그프레스' THEN '기계에 앉아 발판을 다리 힘으로 밀어내는 하체 운동이에요.'
    WHEN '런지' THEN '한 발을 앞으로 내딛고 무릎을 굽혀 앉았다 일어서는 하체 운동이에요.'
    WHEN '레그컬' THEN '기계에 엎드리거나 앉아 발목으로 패드를 뒤로 당겨 접는 운동이에요. 허벅지 뒤쪽을 씁니다.'
    WHEN '레그익스텐션' THEN '기계에 앉아 발등으로 패드를 밀어 무릎을 펴는 운동이에요. 허벅지 앞쪽을 씁니다.'
    WHEN '힙쓰러스트' THEN '등을 벤치에 기대고 골반 위에 바벨을 올린 뒤 엉덩이를 들어 올리는 운동이에요.'
    WHEN '바벨 컬' THEN '바벨을 잡고 팔꿈치를 굽혀 들어 올리는 이두 운동이에요.'
    WHEN '덤벨 컬' THEN '양손 덤벨을 팔꿈치를 굽혀 들어 올리는 이두 운동이에요.'
    WHEN '해머 컬' THEN '덤벨을 세로로(망치 쥐듯) 잡고 팔꿈치를 굽혀 들어 올리는 운동이에요.'
    WHEN '트라이셉스 익스텐션' THEN '케이블을 아래로 눌러 팔꿈치를 펴는 삼두 운동이에요.'
    WHEN '플랭크' THEN '팔꿈치와 발끝으로 몸을 일직선으로 버티는 코어 운동이에요. 횟수 대신 시간으로 합니다.'
    WHEN '크런치' THEN '누워서 상체를 살짝 말아 올리는 복부 운동이에요.'
    WHEN '행잉 레그레이즈' THEN '철봉에 매달려 다리를 앞으로 들어 올리는 복부 운동이에요.'
    WHEN '케이블 크런치' THEN '케이블을 잡고 무릎 꿇은 자세에서 상체를 말아 내리는 복부 운동이에요.'
    WHEN '러닝' THEN '일정 속도로 달리는 유산소 운동이에요. 시간·거리로 기록합니다.'
    WHEN '사이클' THEN '실내 자전거 페달을 밟는 유산소 운동이에요. 무릎 부담이 적습니다.'
    WHEN '로잉머신' THEN '노 젓듯 손잡이를 당기며 다리로 밀어내는 전신 유산소 운동이에요.'
    WHEN '폼롤러 스트레칭' THEN '폼롤러 위에 근육을 올리고 굴려 뭉친 곳을 풀어주는 이완 동작이에요.'
    WHEN '요가 스트레칭' THEN '호흡에 맞춰 자세를 유지하며 몸을 늘려주는 이완 동작이에요.'
    ELSE description
END;
