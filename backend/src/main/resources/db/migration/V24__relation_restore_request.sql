-- 지난 기록 불러오기 요청 (REL-07)
--
-- 종료된 관계의 기록을 되살리려면 양쪽 모두가 요청해야 한다.
-- 공유 기록이라 한쪽이 단독으로 되살리면 상대가 원치 않는 과거를 다시 마주하게 된다.
--
-- 별도 테이블 대신 컬럼 하나로 충분하다 — 요청자는 최대 2명이고,
-- 첫 번째 요청자를 기록해두면 두 번째 요청자가 왔을 때 바로 실행할 수 있다.
-- (같은 사람이 두 번 눌러도 실행되지 않는다)
ALTER TABLE relations ADD COLUMN restore_requested_by BIGINT REFERENCES users (id);
