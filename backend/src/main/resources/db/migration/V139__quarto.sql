-- 4×4 판, 말 16개(속성 4개를 4비트로: 색·모양·크기·속). 상대가 준 말을 내가 놓고, 남은 말 중 하나를
-- 골라 상대에게 준다. 놓은 직후 그 칸을 지나는 줄에 말 넷이 차고 공통 속성이 하나라도 있으면 놓은 사람이 이긴다.
--
-- couple_games 단일 테이블 상속에 얹는다(game_type = 'QUARTO'). V97(길막기)과 같이 전부 nullable —
-- 다른 game_type 행은 이 값이 없다. 컬럼에 quarto_ 를 붙인 이유도 V97 과 같다(형제 서브클래스가 한
-- 컬럼을 나눠 쓰면 JPA 매핑이 충돌한다).

-- 16자. 칸마다 말 번호 16진수 '0'~'f', 빈 칸은 '.'. 남은 말은 따로 적지 않는다 — 판과 받은 말에서 계산한다
ALTER TABLE couple_games ADD COLUMN quarto_board VARCHAR(16);
-- 지금 놓아야 할(상대가 준) 말 0~15. 첫 수(말 주기) 전과 판이 끝난 뒤에는 null
ALTER TABLE couple_games ADD COLUMN quarto_pending INTEGER;
-- 지금까지 둔 수. 0 번째 수는 선공의 "말 주기"뿐이다. 차례는 이 값의 홀짝이 정한다(선공 = 상대)
ALTER TABLE couple_games ADD COLUMN quarto_move_no INTEGER;
-- '1'(판을 연 사람) / '2'(상대) — 이긴 판에만. 끝났는데 비어 있으면 무승부다
ALTER TABLE couple_games ADD COLUMN quarto_winner VARCHAR(1);
-- 이긴 줄의 네 칸 "0,5,10,15" — 이긴 판에만
ALTER TABLE couple_games ADD COLUMN quarto_win_line VARCHAR(16);

-- 수 기록 — 리플레이와 멱등(client_move_id)을 위해 수마다 한 줄. 판당 많아야 17줄이다.
--
-- user_id 에 users FK 를 걸지 않는다. couple_games 가 사람을 '1'/'2' 로 적어 users FK 를 created_by 하나로
-- 묶어 둔 것과 같은 이유다(V86) — 행은 판과 함께 지워지므로(Purger 가 couple_games 보다 먼저 거둔다) 남지 않는다.
CREATE TABLE quarto_moves (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id        BIGINT      NOT NULL REFERENCES couple_games (id),
    move_no        INTEGER     NOT NULL,
    user_id        BIGINT      NOT NULL,
    place          INTEGER,
    give           INTEGER,
    client_move_id VARCHAR(64) NOT NULL,
    created_at     TIMESTAMP   NOT NULL DEFAULT NOW()
);

-- 같은 수 번호가 두 번 저장되면 판이 갈라진 것이다 — 행 잠금이 먼저 막고, 이건 마지막 안전장치다
CREATE UNIQUE INDEX uk_quarto_moves_game_move ON quarto_moves (game_id, move_no);
-- 같은 요청의 재전송은 저장된 결과를 그대로 돌려준다(QuartoService.move)
CREATE UNIQUE INDEX uk_quarto_moves_game_client ON quarto_moves (game_id, client_move_id);
