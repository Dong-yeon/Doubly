-- 유료 재화 — 지갑·원장·스토어 구매·앱 안 상품 카탈로그 (2026-10-13)
--
-- 왜: 스토어에는 재화 묶음만 올리고, 앱 안 상품(우리 이모지 세트, 이후 스티커 팩)은 서버 카탈로그에서 재화 가격으로
-- 판다(docs/CURRENCY_EMOJI_2026-10-13.md). 1 재화 = 100원 고정. 결제로만 생긴다 — 게임·출석·광고로 주지 않는다.
-- 지갑은 개인(커플 공동 아님), 관계를 끊어도 각자 남는다.
--
-- 잔액은 지갑이 들고 원장은 "왜"를 남긴다. 차감은 조건부 UPDATE 한 줄(paid_balance >= :cost)로만 한다 — 읽고 빼서
-- 쓰면 동시 요청에 한 번이 두 번 쓰인다(feature_credits 의 lost update, 같은 문서 §1-3).
-- 원장의 idempotency_key UNIQUE 가 같은 결제·지출·환불이 두 번 반영되는 것을 DB 로 막는다.
--
-- paid_balance 는 음수를 허용한다(결정, §10-2): 환불 회수 때 이미 쓴 재화는 빚으로 남고, 그동안은 지출이 막힌다.
--
-- 삭제 경로: UserDataPurger 가 사람 단위로 지운다(지갑·구매·원장). 관계 삭제와는 무관 — 개인 자산이다.
-- 롤백:
--   drop table currency_ledger; drop table currency_store_purchases; drop table currency_wallets; drop table shop_items;
--   alter table couple_emoji_sets drop column paid_price;
-- (H2 호환 구문만 사용 — 테스트가 동일 마이그레이션을 적용한다)

CREATE TABLE currency_wallets (
    user_id       BIGINT     PRIMARY KEY REFERENCES users (id),
    paid_balance  BIGINT     NOT NULL DEFAULT 0,   -- 결제로 산 것(환불·회수 대상). 음수 허용(위 주석)
    free_balance  BIGINT     NOT NULL DEFAULT 0,   -- 운영 보상용 자리 — 지금은 지급 경로가 없다
    updated_at    TIMESTAMP  NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_currency_wallet_free_nonneg CHECK (free_balance >= 0)
);

CREATE TABLE currency_store_purchases (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id),
    store           VARCHAR(20)  NOT NULL,          -- GOOGLE_PLAY | APP_STORE
    product_id      VARCHAR(100) NOT NULL,          -- currency_39 등
    transaction_id  VARCHAR(255) NOT NULL UNIQUE,   -- 검증 재호출·웹훅 재전송 멱등
    amount          BIGINT       NOT NULL,          -- 지급한 재화 수
    status          VARCHAR(20)  NOT NULL,          -- GRANTED | REVOKED
    created_at      TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP    NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_currency_purchases_user ON currency_store_purchases (user_id);

-- 원장 — append-only. user_id 에 FK 를 두지 않는다: 백그라운드 환불(이모지 생성 실패)이 탈퇴와 경합할 수 있다
-- (ai_usage_logs 와 같은 판단). 대신 UserDataPurger 가 명시적으로 거둔다.
CREATE TABLE currency_ledger (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    entry_type       VARCHAR(20)  NOT NULL,         -- PURCHASE | SPEND | REFUND | REVOKE | GRANT | MIGRATION
    paid_delta       BIGINT       NOT NULL DEFAULT 0,
    free_delta       BIGINT       NOT NULL DEFAULT 0,
    ref_type         VARCHAR(30),                   -- STORE_PURCHASE | EMOJI_SET | ...
    ref_id           VARCHAR(255),
    idempotency_key  VARCHAR(255) NOT NULL UNIQUE,
    created_at       TIMESTAMP    NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_currency_ledger_user ON currency_ledger (user_id, created_at);

-- 앱 안 상품 — 재화 가격. 앱은 값을 하드코딩하지 않고 GET /shop/items 로 받는다.
