-- 사진 틀린그림찾기 (2026-10-14) — docs/spot-diff-design_2026-10-14.md
--
-- 서버(Spring)가 퍼즐 행과 작업 행을 만들고, 별도 Python worker 가 작업을 집어 A/B 이미지를 만든다.
-- couple_games 에 얹지 않는다 — 미리 만들어 두는 판이라 "판 열기 = 행 생성" 모양이 아니고, 두 사람이
-- 각자 푸는 기록(plays)이 따로 있어야 한다.
--
-- JSON 은 TEXT 에 문자열로 담는다(JSONB 는 H2 에서 돌지 않는다 — CLAUDE.md 4절).

CREATE TABLE spot_puzzles (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    couple_id         BIGINT       NOT NULL REFERENCES relations (id),
    -- 일일 모드에서 그날(KST). 무제한 모드는 NULL — NULL 끼리는 UNIQUE 에 걸리지 않는다(H2·PG 동일)
    puzzle_date       DATE,
    -- 원본 사진: POST / MEAL / WORKOUT / PLACE_VISIT + 그 행 id + 그때의 URL. 생성 전(PENDING)에는 비어 있다
    source_type       VARCHAR(20),
    source_id         BIGINT,
    source_url        VARCHAR(1000),
    image_a_url       VARCHAR(1000),
    image_b_url       VARCHAR(1000),
    -- 결과 이미지 크기(px) — 판정이 픽셀 거리로 하므로 정규화 좌표를 되돌릴 때 쓴다
    width             INTEGER,
    height            INTEGER,
    -- 정답 {"diffs":[{"id":0,"kind":"color","cx":..,"cy":..,"r":..}]} — 서버 전용, 응답에 싣지 않는다
    layout_json       TEXT,
    seed              BIGINT,
    level             VARCHAR(10),
    generator_version VARCHAR(20),
    -- PENDING / READY / NOT_ENOUGH_PHOTOS / FAILED / EXPIRED
    status            VARCHAR(20)  NOT NULL,
    -- EXPIRED 일 때 TIME(48시간 지남) / PHOTO_REMOVED(원본이 지워졌거나 더는 공유 상태가 아님)
    expire_reason     VARCHAR(20),
    fail_reason       VARCHAR(500),
    -- 둘 다 다 찾은 시각 — 게임 스트릭이 센다
    completed_at      TIMESTAMP,
    -- 만료 정리 뒤 결과 카드를 이미 보냈는지(두 번 보내지 않게)
    result_posted     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMP    NOT NULL DEFAULT NOW(),
    expires_at        TIMESTAMP    NOT NULL
);

CREATE UNIQUE INDEX uk_spot_puzzles_couple_date ON spot_puzzles (couple_id, puzzle_date);
CREATE INDEX idx_spot_puzzles_couple_created ON spot_puzzles (couple_id, created_at DESC);
CREATE INDEX idx_spot_puzzles_status_expires ON spot_puzzles (status, expires_at);

-- 한 사람의 풀이. user_id 에 users FK 를 걸지 않는다 — 관계 삭제 때 퍼즐과 함께 지워지고, 탈퇴 때는
-- UserDataPurger 가 user_id 로 한 번 더 거둔다(quarto_moves 와 같은 판단)
CREATE TABLE spot_puzzle_plays (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    puzzle_id    BIGINT       NOT NULL REFERENCES spot_puzzles (id),
    user_id      BIGINT       NOT NULL,
    -- 처음 퍼즐 화면을 연 시각 — 서버가 적는다. 시간은 이 값과 finished_at 으로만 잰다
    started_at   TIMESTAMP    NOT NULL,
    finished_at  TIMESTAMP,
    -- 찾은 차이 id "0,3" / 힌트를 받은 차이 id
    found_ids    VARCHAR(40)  NOT NULL DEFAULT '',
    hinted_ids   VARCHAR(40)  NOT NULL DEFAULT '',
    wrong_taps   INTEGER      NOT NULL DEFAULT 0,
    hints_used   INTEGER      NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_spot_puzzle_plays ON spot_puzzle_plays (puzzle_id, user_id);

CREATE TABLE spot_puzzle_taps (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    play_id       BIGINT           NOT NULL REFERENCES spot_puzzle_plays (id),
    -- 같은 요청의 재전송은 저장된 결과를 그대로 돌려준다
    client_tap_id VARCHAR(64)      NOT NULL,
    x             DOUBLE PRECISION NOT NULL,
    y             DOUBLE PRECISION NOT NULL,
    -- HIT(새로 찾음) / REPEAT(이미 찾은 곳 — 오답 아님) / MISS
    result        VARCHAR(10)      NOT NULL,
    hit_id        INTEGER,
    created_at    TIMESTAMP        NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_spot_puzzle_taps_client ON spot_puzzle_taps (client_tap_id);
CREATE INDEX idx_spot_puzzle_taps_play ON spot_puzzle_taps (play_id);

-- 생성 작업 대기열 — worker 가 SELECT ... FOR UPDATE SKIP LOCKED 로 집는다
CREATE TABLE spot_puzzle_jobs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    puzzle_id   BIGINT       NOT NULL REFERENCES spot_puzzles (id),
    -- QUEUED / RUNNING / DONE / FAILED
    status      VARCHAR(10)  NOT NULL,
    -- 후보 사진 [{"type":"POST","id":1,"url":"..."}] — Spring 이 고른 공유 사진. worker 는 크기만 더 본다
    candidates  TEXT         NOT NULL,
    seed        BIGINT       NOT NULL,
    attempts    INTEGER      NOT NULL DEFAULT 0,
    locked_at   TIMESTAMP,
    error       VARCHAR(500),
    created_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP    NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_spot_puzzle_jobs_status ON spot_puzzle_jobs (status, created_at);
CREATE INDEX idx_spot_puzzle_jobs_puzzle ON spot_puzzle_jobs (puzzle_id);

-- 사진 크기 캐시 — 짧은 변 1000px 검사를 매일 같은 사진에 다시 하지 않게(worker 가 채운다).
-- 크기는 EXIF 방향을 적용한 뒤의 값이다. 관계와 무관한 URL 캐시라 Purger 대상이 아니다(URL 만 있고 내용이 없다)
CREATE TABLE spot_photo_sizes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url         VARCHAR(1000) NOT NULL,
    width       INTEGER       NOT NULL,
    height      INTEGER       NOT NULL,
    checked_at  TIMESTAMP     NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX uk_spot_photo_sizes_url ON spot_photo_sizes (url);
