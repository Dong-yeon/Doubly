package com.fitto.common.notification;

/**
 * 푸시 알림 분류 — 설정 화면에서 <b>카테고리 단위로</b> 끄고 켜기 위한 구분.
 *
 * <p><b>왜 필요한가</b>: 푸시 종류가 20종이 넘는데 설정은 "전부 켜거나 전부 끄거나"
 * 하나뿐이었다. 채팅 알림 하나가 성가시다는 이유로 전체를 꺼버리면 기념일도 상대
 * 활동도 같이 사라진다 — 알림 피로가 곧 이탈로 이어지는 구조였다.
 *
 * <p>분류는 <b>사용자가 체감하는 성가심의 결</b>로 나눈다. 보내는 쪽 도메인(운동/식단/
 * 맛집…)으로 나누면 설정 화면이 20줄이 되고, 어느 것을 꺼야 조용해지는지 알 수 없다.
 */
public enum NotificationCategory {

    /** 채팅·통화 — 사람이 나를 직접 부르는 알림. 즉시성이 가장 높다. */
    CHAT,

    /** 기념일·캘린더 D-day — 놓치면 되돌릴 수 없는 날짜 알림. */
    ANNIVERSARY,

    /** 상대(또는 트레이너)의 활동 — 운동·식단·피드·맛집·선물처럼 "상대가 뭔가 했다". */
    PARTNER,

    /** 앱이 먼저 부르는 리마인드 — 스트릭 위기·미답변 질문·추억처럼 사람이 트리거하지 않은 것. */
    REMINDER
}
