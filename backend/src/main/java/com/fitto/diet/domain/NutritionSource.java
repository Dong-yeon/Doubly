package com.fitto.diet.domain;

/**
 * 끼니의 칼로리·매크로가 어디서 왔는지.
 *
 * <p>운동 인증샷은 "AI 결과를 자동 저장하지 않는다"를 원칙으로 삼았다
 * ({@code docs/WORKOUT_LOOSE_DIRECTION_2026-09-09.md} 4절) — 거기서 AI 가 읽는 건 화면에
 * <b>인쇄된 사실</b>(5.2km)이라 잘못 읽으면 사실이 왜곡되기 때문이다. 음식 사진은 다르다.
 * 칼로리는 애초에 사실이 아니라 추정이고, 사용자가 손으로 적는 값도 똑같이 추정이다.
 * 그래서 자동 저장은 허용하되, 원칙의 취지("무엇이 진짜였는지 알 수 있어야 한다")를
 * 이 값으로 대신 지킨다.
 *
 * <p>{@code null} 은 사용자 입력이다 — 이 컬럼이 생기기 전의 모든 기록이 그렇고,
 * 굳이 백필하지 않는다({@link #USER} 와 같은 뜻).
 */
public enum NutritionSource {

    /** 사용자가 직접 적었거나, 자동 분석 결과를 한 번이라도 손봤다. 배지를 띄우지 않는다. */
    USER,

    /** 사진 저장 직후 백그라운드 AI 가 채웠고 아직 사용자가 확인하지 않았다. */
    AI_ESTIMATED
}
